-- 0015_login_state_terms.sql — какую редакцию соглашения видел человек,
-- уходя к провайдеру.
--
-- Акцепт даётся действием: человек читает юридическую строку на нашем
-- экране и нажимает кнопку провайдера. Записать это можно только
-- вернувшись — а к моменту возврата экран уже не существует.
--
-- Редакцию приносит сам экран и она едет вместе с одноразовым
-- состоянием этой попытки входа. Не из настроек, не «текущая на момент
-- возврата»: записать надо то, что человек ВИДЕЛ.
--
-- NULL допустим: так выглядит уход к провайдеру со старого экрана,
-- который редакции не называл. Записи об акцепте в этом случае не
-- будет — придумывать её задним числом нельзя.
ALTER TABLE provider_login_states ADD COLUMN terms_version text;
